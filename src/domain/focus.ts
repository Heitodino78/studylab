import type { Data, FocusState, Item, Preferences } from '../models';

/**
 * Focus timer domain: pure functions over `FocusState` and `Data`.
 *
 * The timer never counts ticks. Time is derived from timestamps:
 *   elapsed = accumulatedMs + (now - startedAt)   while running
 * so a throttled background tab or a page reload cannot change the result.
 */

export const MINUTE_MS = 60_000;
/** Sessions shorter than this are discarded instead of being recorded. */
const MIN_SESSION_MS = 1_000;

type Phase = FocusState['phase'];

/** Configured length, in minutes, of a Pomodoro phase. */
export function phaseMinutes(settings: Preferences, phase: Phase): number {
  const { focusMinutes, shortBreakMinutes, longBreakMinutes } = settings.pomodoro;
  if (phase === 'focus') return focusMinutes;
  return phase === 'shortBreak' ? shortBreakMinutes : longBreakMinutes;
}

/** Total time on the clock for the current phase. Clock going backwards counts as zero. */
export function elapsedMs(state: FocusState, now: number): number {
  const running = state.startedAt === null ? 0 : Math.max(0, now - state.startedAt);
  return Math.max(0, state.accumulatedMs + running);
}

/** Target length of the phase, or null for the free stopwatch. */
export function targetMs(state: FocusState): number | null {
  return state.mode === 'pomodoro' ? state.durationMinutes * MINUTE_MS : null;
}

/** Time that may be credited: never more than the Pomodoro target. */
export function countedMs(state: FocusState, now: number): number {
  const elapsed = elapsedMs(state, now);
  const target = targetMs(state);
  return target === null ? elapsed : Math.min(elapsed, target);
}

export function remainingMs(state: FocusState, now: number): number | null {
  const target = targetMs(state);
  return target === null ? null : Math.max(0, target - elapsedMs(state, now));
}

export const isRunning = (state: FocusState): boolean => state.startedAt !== null;
export const isIdle = (state: FocusState): boolean => state.startedAt === null && state.accumulatedMs === 0;

export function isPhaseFinished(state: FocusState, now: number): boolean {
  const target = targetMs(state);
  return target !== null && elapsedMs(state, now) >= target;
}

/** "Cycle 2 of 4" shown to the user; breaks refer to the cycle that just ended. */
export function cycleNumber(state: FocusState, settings: Preferences): number {
  const length = settings.pomodoro.cyclesBeforeLongBreak;
  return state.phase === 'focus' ? (state.cycle % length) + 1 : ((Math.max(1, state.cycle) - 1) % length) + 1;
}

// ---------------------------------------------------------------- transitions

/** Start from idle or continue after a pause. Idle phases pick up the latest settings. */
export function startOrResume(state: FocusState, settings: Preferences, now: number): FocusState {
  if (isRunning(state)) return state;
  const durationMinutes = isIdle(state) && state.mode === 'pomodoro' ? phaseMinutes(settings, state.phase) : state.durationMinutes;
  return { ...state, durationMinutes, startedAt: now };
}

export function pause(state: FocusState, now: number): FocusState {
  if (!isRunning(state)) return state;
  return { ...state, accumulatedMs: countedMs(state, now), startedAt: null };
}

/** Discards the time of the current phase and prepares a fresh, stopped one. */
export function resetPhase(state: FocusState, settings: Preferences, newId: string): FocusState {
  const durationMinutes = state.mode === 'pomodoro' ? phaseMinutes(settings, state.phase) : state.durationMinutes;
  return { ...state, id: newId, startedAt: null, accumulatedMs: 0, durationMinutes };
}

/** Switches between Pomodoro and stopwatch; only meaningful while idle. */
export function switchMode(state: FocusState, mode: FocusState['mode'], settings: Preferences, newId: string): FocusState {
  return {
    ...state,
    id: newId,
    mode,
    phase: 'focus',
    cycle: 0,
    startedAt: null,
    accumulatedMs: 0,
    durationMinutes: phaseMinutes(settings, 'focus'),
  };
}

export function setSubject(state: FocusState, subjectId: string): FocusState {
  return { ...state, subjectId };
}

// ------------------------------------------------------------------ completion

export interface CompleteOptions {
  /** Id of the phase the caller saw; a different id means someone else already completed it. */
  expectedPhaseId: string;
  now: number;
  /** Id for the next phase (generated by the caller so the update function stays pure). */
  newId: string;
  /** Complete before the target (manual "register session" / "skip break"). */
  force?: boolean;
}

/** When the credited time ended: the moment the target was reached, not when the page noticed. */
function creditedEnd(state: FocusState, credited: number, now: number): number {
  if (state.startedAt === null) return now;
  return Math.max(state.startedAt, state.startedAt + (credited - state.accumulatedMs));
}

function addSession(data: Data, state: FocusState, credited: number, endedAt: number): Item[] {
  const id = `session-${state.id}`; // deterministic: replays and recoveries cannot duplicate
  if (credited < MIN_SESSION_MS || data.sessions.some(session => session.id === id)) return data.sessions;
  const subjectExists = state.subjectId !== '' && data.subjects.some(subject => subject.id === state.subjectId);
  const session: Item = {
    id,
    title: state.mode === 'pomodoro' ? 'Sessão de foco' : 'Cronômetro livre',
    createdAt: endedAt,
    duration: credited,
    ...(subjectExists ? { subjectId: state.subjectId } : {}),
  };
  return [...data.sessions, session];
}

function freshPhase(state: FocusState, phase: Phase, cycle: number, minutes: number, newId: string): FocusState {
  return { ...state, id: newId, phase, cycle, startedAt: null, accumulatedMs: 0, durationMinutes: minutes };
}

/**
 * Completes the current phase inside an atomic update. Idempotent: if the phase id no longer
 * matches (already completed here, in another tab, or after a reload) the data is returned as is.
 *
 * - Pomodoro focus: credits at most the target, then prepares a STOPPED break.
 * - Break: nothing is credited; prepares a stopped focus phase.
 * - Stopwatch: credits everything and returns to idle.
 */
export function completePhase(data: Data, options: CompleteOptions): Data {
  const { focus, settings } = data;
  if (focus.id !== options.expectedPhaseId) return data;
  if (!options.force && !isPhaseFinished(focus, options.now)) return data;

  const { newId } = options;
  if (focus.phase !== 'focus') {
    return { ...data, focus: freshPhase(focus, 'focus', focus.cycle, phaseMinutes(settings, 'focus'), newId) };
  }

  const credited = countedMs(focus, options.now);
  const sessions = addSession(data, focus, credited, creditedEnd(focus, credited, options.now));

  if (focus.mode === 'stopwatch') {
    return { ...data, sessions, focus: freshPhase(focus, 'focus', focus.cycle, focus.durationMinutes, newId) };
  }
  const target = targetMs(focus) ?? 0;
  if (credited < target) {
    // Finished early by the user: keep the time, stay on focus, do not advance the cycle.
    return { ...data, sessions, focus: freshPhase(focus, 'focus', focus.cycle, phaseMinutes(settings, 'focus'), newId) };
  }
  const cycle = focus.cycle + 1;
  const next: Phase = cycle % settings.pomodoro.cyclesBeforeLongBreak === 0 ? 'longBreak' : 'shortBreak';
  return { ...data, sessions, focus: freshPhase(focus, next, cycle, phaseMinutes(settings, next), newId) };
}

/** True when `completePhase` would change something for this state (used to avoid useless writes). */
export function needsCompletion(state: FocusState, now: number): boolean {
  return isPhaseFinished(state, now);
}

// -------------------------------------------------------------------- settings

export const PREFERENCE_LIMITS = {
  displayName: 60,
  dailyMinutes: [1, 1440],
  weeklyMinutes: [1, 10080],
  focusMinutes: [1, 180],
  shortBreakMinutes: [1, 60],
  longBreakMinutes: [1, 120],
  cyclesBeforeLongBreak: [1, 12],
} as const;

export type PreferenceField = keyof typeof PREFERENCE_LIMITS;
type NumericField = Exclude<PreferenceField, 'displayName'>;
export type PreferenceErrors = Partial<Record<PreferenceField, string>>;

function checkInteger(value: number, [min, max]: readonly [number, number], label: string): string | undefined {
  if (!Number.isInteger(value)) return `${label}: informe um número inteiro.`;
  if (value < min || value > max) return `${label}: use um valor entre ${min} e ${max}.`;
  return undefined;
}

/** Returns one message per invalid field; an empty object means the preferences can be saved. */
export function validatePreferences(preferences: Preferences): PreferenceErrors {
  const errors: PreferenceErrors = {};
  const { pomodoro } = preferences;
  const checks: [NumericField, number, string][] = [
    ['dailyMinutes', preferences.dailyMinutes, 'Meta diária (min)'],
    ['weeklyMinutes', preferences.weeklyMinutes, 'Meta semanal (min)'],
    ['focusMinutes', pomodoro.focusMinutes, 'Foco (min)'],
    ['shortBreakMinutes', pomodoro.shortBreakMinutes, 'Pausa curta (min)'],
    ['longBreakMinutes', pomodoro.longBreakMinutes, 'Pausa longa (min)'],
    ['cyclesBeforeLongBreak', pomodoro.cyclesBeforeLongBreak, 'Ciclos até a pausa longa'],
  ];
  for (const [field, value, label] of checks) {
    const message = checkInteger(value, PREFERENCE_LIMITS[field], label);
    if (message) errors[field] = message;
  }
  if (preferences.displayName.trim().length > PREFERENCE_LIMITS.displayName) {
    errors.displayName = `Nome: use no máximo ${PREFERENCE_LIMITS.displayName} caracteres.`;
  }
  if (!errors.dailyMinutes && !errors.weeklyMinutes && preferences.weeklyMinutes < preferences.dailyMinutes) {
    errors.weeklyMinutes = 'Meta semanal (min): não pode ser menor que a meta diária.';
  }
  return errors;
}
